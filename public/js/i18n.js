export const LANGS = Object.keys(STRINGS);

export function translator(lang) {
  const dict = STRINGS[lang] ?? STRINGS.en;
  return (key, params) => {
    let s = dict[key];
    if (s == null) {
      s = STRINGS.en[key];
      if (s == null) return `!${key}`;
    }
    if (!params) return s;
    return s.replace(/\{(\w+)\}/g, (m, name) => (params[name] != null ? String(params[name]) : m));
  };
}

export function keysFor(lang) {
  return Object.keys(STRINGS[lang] ?? {});
}

export function missingIn(lang) {
  const have = new Set(keysFor(lang));
  return Object.keys(STRINGS.en).filter((k) => !have.has(k));
}
